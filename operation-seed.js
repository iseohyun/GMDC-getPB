/**
 * Removes parentheses and their contents from title for clean calendar display
 */
export function cleanTitle(str) {
  if (!str) return '';
  return String(str).replace(/\s*\([^)]*\)/g, '').trim();
}

/**
 * Category to Badge Class Mapping
 */
export function getCategoryBadgeClass(category) {
  switch (category) {
    case '훈련일정': return 'badge-cat-training';
    case '운영회의':
    case '임원회의':
    case '대표자회의': return 'badge-cat-meeting';
    case '대회일정':
    case '대회공지': return 'badge-cat-notice';
    case '이벤트':
    case '정산보고':
    case '기타': return 'badge-cat-event';
    default: return 'badge-cat-other';
  }
}

/**
 * Maps category to calendar pill type & icon
 */
export function mapCategoryToTypeAndIcon(category) {
  if (category === '훈련일정') {
    return { type: 'training', icon: '🏊 ' };
  } else if (category === '운영회의' || category === '대표자회의' || category === '임원회의') {
    return { type: 'meeting', icon: '👥 ' };
  } else if (category === '대회일정' || category === '대회공지') {
    return { type: 'comp', icon: '📢 ' };
  } else if (category === '이벤트' || category === '정산보고' || category === '기타') {
    return { type: 'event', icon: '✉️ ' };
  }
  return { type: 'notice', icon: '📝 ' };
}

/**
 * Converts logs array into calendar events date-map
 */
